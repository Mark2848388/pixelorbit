-- Pixel Orbit Infinite v4.5 — Web Push subscriptions
-- Apply once in Supabase SQL Editor after reviewing the v4.4 schema.
create table if not exists public.push_subscriptions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  endpoint text not null,
  subscription jsonb not null,
  updated_at timestamptz not null default now(),
  unique(user_id, endpoint)
);
create index if not exists push_subscriptions_user_id_idx on public.push_subscriptions(user_id);
alter table public.push_subscriptions enable row level security;
drop policy if exists "pilots manage own push subscriptions" on public.push_subscriptions;
create policy "pilots manage own push subscriptions" on public.push_subscriptions
  for all to authenticated using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);
grant select,insert,update,delete on public.push_subscriptions to authenticated;
grant usage,select on sequence public.push_subscriptions_id_seq to authenticated;
